from __future__ import annotations

from dataclasses import dataclass, replace
from enum import Enum
from types import MappingProxyType
from typing import TYPE_CHECKING, Callable, Dict, Iterable, Optional, Sequence, Tuple

if TYPE_CHECKING:
    from vascx.shared.features import Feature, FeatureSet


class NamingConvention(str, Enum):
    CANONICAL = "canonical"
    RESOLVED = "resolved"


@dataclass(frozen=True)
class NamePart:
    key: str
    tokens: Tuple[str, ...]
    display: str = ""
    annotation: bool = False
    family: bool = False
    always_keep: bool = False
    resolution_scope: Optional[str] = None


@dataclass(frozen=True)
class FeatureName:
    feature_index: int
    target_name: str
    name: str
    display_name: str
    component: str = ""


def coerce_naming_convention(value: NamingConvention | str) -> NamingConvention:
    if isinstance(value, NamingConvention):
        return value
    try:
        return NamingConvention(value)
    except ValueError as exc:
        choices = ", ".join(item.value for item in NamingConvention)
        raise ValueError(f"Unknown naming convention '{value}'; choose {choices}") from exc


def _join_name_parts(parts: Sequence[NamePart], active_keys: set[str]) -> str:
    return "_".join(
        token
        for part in parts
        if part.key in active_keys
        for token in part.tokens
        if token
    )


def _humanize_token(token: str) -> str:
    return token.replace("_", " ").replace("p", ".").title()


def _join_display_parts(parts: Sequence[NamePart], active_keys: set[str]) -> str:
    main = " ".join(
        part.display
        for part in parts
        if part.key in active_keys and not part.annotation and part.display
    )
    annotations = [
        part.display
        for part in parts
        if part.key in active_keys and part.annotation and part.display
    ]
    main = " ".join(main.split())
    main = main.replace("]  -", "] -")
    if annotations:
        main = f"{main} ({'; '.join(annotations)})" if main else "; ".join(annotations)
    return main


def _make_names(
    feature_set: "FeatureSet",
    target_names_for_feature: Callable[["Feature"], Iterable[str]],
    naming: NamingConvention | str = NamingConvention.CANONICAL,
    *, expand_outputs: bool = False,
) -> Dict[Tuple[int, str] | Tuple[int, str, str], FeatureName]:
    """Build canonical or feature-set-resolved names for a feature set."""

    convention = coerce_naming_convention(naming)
    records = []
    identities = []
    for feature_index, feature in enumerate(feature_set):
        for target_name in target_names_for_feature(feature):
            components = [item.key for item in feature.output_schema()] if expand_outputs else [""]
            for component in components:
                parts = tuple(feature.output_name_parts(component, layer_name=target_name))
                if not any(part.family for part in parts):
                    parts = (replace(parts[0], family=True), *parts[1:])
                records.append((feature_index, target_name, feature, parts))
                identities.append((feature_index, target_name, component) if expand_outputs
                                  else (feature_index, target_name))

    canonical_names: Dict[str, Tuple[int, Feature]] = {}
    for feature_index, _, feature, parts in records:
        key = _join_name_parts(parts, {part.key for part in parts})
        if key in canonical_names:
            previous = canonical_names[key]
            raise ValueError(
                f"Duplicate canonical feature name '{key}' generated by feature "
                f"indices {previous[0]} and {feature_index}"
            )
        canonical_names[key] = (feature_index, feature)

    active = [{part.key for part in parts} for _, _, _, parts in records]
    if convention == NamingConvention.RESOLVED:
        families: Dict[Tuple[type, Tuple[str, ...]], list[int]] = {}
        for index, (_, _, feature, parts) in enumerate(records):
            family_part = next(part for part in parts if part.family)
            families.setdefault((feature.__class__, family_part.tokens), []).append(index)

        for family_indices in families.values():
            part_keys = []
            for part in records[family_indices[0]][3]:
                if part.key not in part_keys:
                    part_keys.append(part.key)
            for part_key in part_keys:
                part_template = next(
                    part for index in family_indices for part in records[index][3]
                    if part.key == part_key
                )
                if part_template.always_keep:
                    continue

                scopes = [family_indices]
                if part_template.resolution_scope == "grid":
                    grid_groups = {}
                    for index in family_indices:
                        grid_signature = next(
                            (part.tokens for part in records[index][3] if part.key == "grid"),
                            (),
                        )
                        grid_groups.setdefault(grid_signature, []).append(index)
                    scopes = list(grid_groups.values())

                family_part = any(
                    part.key == part_key and part.family
                    for index in family_indices
                    for part in records[index][3]
                )
                if family_part:
                    continue
                for scope_indices in scopes:
                    signatures = {
                        next(
                            (part.tokens for part in records[index][3] if part.key == part_key),
                            (),
                        )
                        for index in scope_indices
                    }
                    if len(signatures) == 1:
                        for index in scope_indices:
                            active[index].discard(part_key)

    def current_names() -> Dict[str, list[int]]:
        grouped: Dict[str, list[int]] = {}
        for index, record in enumerate(records):
            grouped.setdefault(_join_name_parts(record[3], active[index]), []).append(index)
        return grouped

    while True:
        duplicates = [indices for indices in current_names().values() if len(indices) > 1]
        if not duplicates:
            break
        changed = False
        for indices in duplicates:
            candidate_keys = [
                part.key
                for part in records[indices[0]][3]
                if part.key not in active[indices[0]]
            ]
            for part_key in candidate_keys:
                signatures = {
                    next(
                        (part.tokens for part in records[index][3] if part.key == part_key),
                        (),
                    )
                    for index in indices
                }
                if len(signatures) > 1:
                    for index in indices:
                        if any(part.key == part_key for part in records[index][3]):
                            active[index].add(part_key)
                    changed = True
                    break
        if not changed:
            raise ValueError("Resolved feature names are not unique within the feature set")

    result = {}
    display_groups = {}
    for index, (feature_index, target_name, _, parts) in enumerate(records):
        name = _join_name_parts(parts, active[index])
        display = _join_display_parts(parts, active[index]) or name
        key = identities[index]
        result[key] = FeatureName(feature_index, target_name, name, display,
                                  key[2] if expand_outputs else "")
        display_groups.setdefault(display, []).append(key)
    for keys in display_groups.values():
        if len(keys) > 1:
            for key in keys:
                item = result[key]
                result[key] = replace(item, display_name=f"{item.display_name} [{item.name}]")
    return result


def make_feature_names(
    feature_set: "FeatureSet",
    target_names_for_feature: Callable[["Feature"], Iterable[str]],
    naming: NamingConvention | str = NamingConvention.CANONICAL,
) -> Dict[Tuple[int, str], FeatureName]:
    """Names of feature groups, keyed by (feature index, target)."""
    return _make_names(feature_set, target_names_for_feature, naming)


def make_output_names(
    feature_set: "FeatureSet",
    target_names_for_feature: Callable[["Feature"], Iterable[str]],
    naming: NamingConvention | str = NamingConvention.CANONICAL,
) -> Dict[Tuple[int, str, str], FeatureName]:
    """Names of scalar output columns, keyed by (feature index, target, component)."""
    return _make_names(feature_set, target_names_for_feature, naming, expand_outputs=True)


@dataclass(frozen=True)
class FeatureBinding:
    """One named output and the configured feature, target and component behind it."""

    feature: "Feature"
    feature_index: int
    target: str
    component: str
    name: str
    display_name: str
    canonical_name: str
    resolved_name: str


@dataclass(frozen=True)
class FeatureSetNames:
    """Read-only views of a feature set's group names, output names and bindings."""

    _groups: dict
    _outputs: dict
    _by_name: dict

    @property
    def groups(self):
        return MappingProxyType(self._groups)

    @property
    def outputs(self):
        return MappingProxyType(self._outputs)

    @property
    def by_name(self):
        return MappingProxyType(self._by_name)


def build_feature_set_names(feature_set: "FeatureSet", targets: tuple) -> dict:
    """Build both conventions together for one complete set and target layout."""
    targets_by_feature = {id(feature): names for feature, names in zip(feature_set, targets)}

    def target_names(feature):
        return targets_by_feature[id(feature)]

    outputs = {
        convention: make_output_names(feature_set, target_names, convention)
        for convention in NamingConvention
    }
    result = {}
    for convention in NamingConvention:
        bindings = {}
        for key, item in outputs[convention].items():
            index, target, component = key
            bindings[item.name] = FeatureBinding(
                feature=feature_set.features[index],
                feature_index=index,
                target=target,
                component=component,
                name=item.name,
                display_name=item.display_name,
                canonical_name=outputs[NamingConvention.CANONICAL][key].name,
                resolved_name=outputs[NamingConvention.RESOLVED][key].name,
            )
        result[convention] = FeatureSetNames(
            make_feature_names(feature_set, target_names, convention),
            outputs[convention],
            bindings,
        )
    return result
